#include<stdio.h>
int main(){
printf("%d\n",1 == 2); //this will return 0 / False
printf("%d\n",1 != 2); //this will return 1 / True
printf("%d\n",1 > 2); //this will return 0 / False
printf("%d\n",1 < 2); //this will return 1 / True
printf("%d\n",1 >= 2); //this will return 0 / False
printf("%d\n",1 <= 2); //this will return 1 / True
return 0;
}
